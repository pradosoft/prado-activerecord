   Loaded into prado_unitest.fdb by .github/scripts/setup-firebird.sh (isql as SYSDBA).
   A plain DROP on a fresh database raises SQLCODE -607; the setup script ignores that
   and checks the departments table afterwards.
   Firebird stores these unquoted identifiers in upper case; FirebirdConnectionTrait
   lower-cases result column names. DEFAULT comes before NOT NULL in a column definition.
   Same tables and rows as scripts/mysql/database.sql. */

DROP TABLE departments;
CREATE TABLE departments (
  department_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 9) PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  description VARCHAR(1000),
  active BOOLEAN DEFAULT FALSE NOT NULL,
  sort_key SMALLINT DEFAULT 0 NOT NULL
);

