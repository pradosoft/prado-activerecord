-- Run as prado_unitest by .github/scripts/setup-oracle.sh (sqlplus); requires Oracle 23c+
-- for DROP TABLE IF EXISTS. CI uses gvenzl/oracle-free 23.
-- Oracle stores these unquoted identifiers in upper case; TOracleMetaData reports the
-- column names in lower case and never quotes them, so no column may be a reserved word.
-- Same tables and rows as scripts/mysql/database.sql.

