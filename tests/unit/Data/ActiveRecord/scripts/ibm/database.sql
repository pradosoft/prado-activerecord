-- ActiveRecord test schema for IBM DB2.
-- Loaded into the pradount database as db2inst1 by .github/scripts/setup-ibm.sh
-- (db2 -td\; -f). A plain DROP on a fresh database raises SQL0204N; the setup script
-- ignores that and checks the departments table afterwards.
-- DB2 stores these unquoted identifiers in upper case; IbmConnectionTrait lower-cases
-- result column names.
-- Same tables and rows as scripts/mysql/database.sql.

DROP TABLE departments;
CREATE TABLE departments (
  department_id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  name VARCHAR(255) NOT NULL,
  description VARCHAR(1000),
  active SMALLINT NOT NULL DEFAULT 0,
  sort_key SMALLINT NOT NULL DEFAULT 0,
  PRIMARY KEY (department_id)
);

